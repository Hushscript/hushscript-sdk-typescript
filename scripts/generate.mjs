// Regenerates openapi.json and everything under src/generated/ from the API spec and the
// conformance repo's hints.json. Runs only in the `regen` compose service (`just regen`).
//
//   node scripts/generate.mjs [specPathOrUrl]     default: https://api.hushscript.com/openapi.json
//
// hints.json comes from $CONFORMANCE_DIR/hints.json when set, otherwise from the conformance repo
// at the tag or commit in package.json `config.conformanceRef`.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const DEFAULT_SPEC = "https://api.hushscript.com/openapi.json";
const HTTP_METHODS = ["get", "put", "post", "delete", "options", "head", "patch", "trace"];
const HEADER =
  "// Generated by scripts/generate.mjs from openapi.json and the conformance hints.json. Do not edit.\n";

const root = new URL("../", import.meta.url);
const rootPath = (/** @type {string} */ relative) => fileURLToPath(new URL(relative, root));

/**
 * @param {unknown} value
 * @param {string} what
 * @returns {Record<string, unknown>}
 */
export function asRecord(value, what) {
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    throw new Error(`${what} must be an object`);
  }
  return /** @type {Record<string, unknown>} */ (value);
}

/**
 * @param {unknown} value
 * @param {string} what
 * @returns {string}
 */
function asString(value, what) {
  if (typeof value !== "string" || value === "")
    throw new Error(`${what} must be a non-empty string`);
  return value;
}

/**
 * @param {unknown} value
 * @param {string} what
 * @returns {number}
 */
function asInteger(value, what) {
  if (typeof value !== "number" || !Number.isInteger(value))
    throw new Error(`${what} must be an integer`);
  return value;
}

/**
 * The error catalog as a lookup table by slug.
 * @param {unknown} spec
 * @returns {string}
 */
export function emitCatalog(spec) {
  const catalog = asRecord(spec, "spec")["x-error-catalog"];
  if (!Array.isArray(catalog) || catalog.length === 0)
    throw new Error("spec has no x-error-catalog");
  const seen = new Set();
  const lines = catalog.map((/** @type {unknown} */ raw, /** @type {number} */ index) => {
    const entry = asRecord(raw, `x-error-catalog[${String(index)}]`);
    const slug = asString(entry["slug"], `x-error-catalog[${String(index)}].slug`);
    if (seen.has(slug)) throw new Error(`duplicate error slug ${slug}`);
    seen.add(slug);
    const code = asInteger(entry["code"], `${slug}.code`);
    const status = asInteger(entry["status"], `${slug}.status`);
    const meaning = asString(entry["meaning"], `${slug}.meaning`);
    return `  ${JSON.stringify(slug)}: { code: ${String(code)}, status: ${String(status)}, meaning: ${JSON.stringify(meaning)} },`;
  });
  return `${HEADER}
export interface ErrorCatalogEntry {
  code: number;
  status: number;
  meaning: string;
}

export const ERROR_CATALOG: Record<string, ErrorCatalogEntry> = {
${lines.join("\n")}
};
`;
}

/**
 * The scope each operation needs, keyed "METHOD /path".
 * @param {unknown} spec
 * @returns {string}
 */
export function emitScopes(spec) {
  const paths = asRecord(asRecord(spec, "spec")["paths"], "paths");
  /** @type {[string, string][]} */
  const entries = [];
  for (const [path, item] of Object.entries(paths)) {
    const operations = asRecord(item, `paths.${path}`);
    for (const method of HTTP_METHODS) {
      const operation = operations[method];
      if (operation === undefined) continue;
      const scope = asRecord(operation, `${method} ${path}`)["x-required-scope"];
      if (scope === undefined) continue;
      entries.push([
        `${method.toUpperCase()} ${path}`,
        asString(scope, `${method} ${path} x-required-scope`),
      ]);
    }
  }
  entries.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  const lines = entries.map(
    ([key, scope]) => `  ${JSON.stringify(key)}: ${JSON.stringify(scope)},`,
  );
  return `${HEADER}
export const OPERATION_SCOPES: Record<string, string> = {
${lines.join("\n")}
};
`;
}

/**
 * The shared English hint text, keyed by error slug.
 * @param {unknown} hints
 * @returns {string}
 */
export function emitHints(hints) {
  const table = asRecord(hints, "hints.json");
  const lines = Object.entries(table).map(
    ([slug, text]) =>
      `  ${JSON.stringify(slug)}: ${JSON.stringify(asString(text, `hints.${slug}`))},`,
  );
  if (lines.length === 0) throw new Error("hints.json is empty");
  return `${HEADER}
export const HINTS: Record<string, string> = {
${lines.join("\n")}
};
`;
}

/**
 * @param {string} url
 * @returns {Promise<string>}
 */
async function fetchText(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(60_000) });
  if (!response.ok) throw new Error(`GET ${url} answered ${String(response.status)}`);
  return response.text();
}

/**
 * @param {string} text
 * @returns {unknown}
 */
function parseJson(text) {
  return JSON.parse(text);
}

/** @returns {Promise<unknown>} */
async function loadHints() {
  const dir = process.env["CONFORMANCE_DIR"];
  if (dir !== undefined && dir !== "") {
    return parseJson(readFileSync(`${dir}/hints.json`, "utf8"));
  }
  const pkg = asRecord(parseJson(readFileSync(rootPath("package.json"), "utf8")), "package.json");
  const ref = asString(
    asRecord(pkg["config"], "package.json config")["conformanceRef"],
    "config.conformanceRef",
  );
  const url = `https://raw.githubusercontent.com/Hushscript/hushscript-sdk-conformance/${ref}/hints.json`;
  return parseJson(await fetchText(url));
}

/**
 * The spec's own bytes, so key order and formatting survive and the regen diff stays reviewable.
 * @param {string} source
 * @returns {Promise<string>}
 */
function loadSpecText(source) {
  if (/^https?:\/\//.test(source)) return fetchText(source);
  return Promise.resolve(readFileSync(source, "utf8"));
}

/** @param {string | undefined} source */
export async function generate(source = DEFAULT_SPEC) {
  const specText = await loadSpecText(source);
  const spec = parseJson(specText);
  const hints = await loadHints();
  const catalog = emitCatalog(spec);
  const scopes = emitScopes(spec);
  const hintsTable = emitHints(hints);

  writeFileSync(rootPath("openapi.json"), specText.endsWith("\n") ? specText : `${specText}\n`);
  execFileSync(
    rootPath("node_modules/.bin/openapi-typescript"),
    ["openapi.json", "-o", "src/generated/schema.d.ts"],
    { cwd: rootPath("."), stdio: "inherit" },
  );
  writeFileSync(rootPath("src/generated/catalog.ts"), catalog);
  writeFileSync(rootPath("src/generated/scopes.ts"), scopes);
  writeFileSync(rootPath("src/generated/hints.ts"), hintsTable);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await generate(process.argv[2]);
}
